#!/usr/bin/env python3
"""
Regenerate the main NER results table with multi-seed means.

Two things this fixes relative to the hand-written table it replaces:

1. Our row becomes mean +- std over training seeds. Single-seed CORD varies by
   2.85 F1 across seeds, so a single number was never a stable claim.

2. It adds the word-level re-annotated benchmarks. The published FUNSD/CORD
   numbers use SEGMENT-level layout positions, where all words in a
   ground-truth segment share one 2D position -- which leaks the entity
   grouping. LayoutLMv3's own paper states the two protocols are "not directly
   comparable". On the word-level re-annotations (FUNSD-r / CORD-r, Zhang et
   al., EMNLP 2023), sequence labeling with a LayoutLMv3-base backbone scores
   78.77 / 82.72 (verified against Table 1 of that paper). Our numbers sit where word-level numbers sit, and omitting
   this makes the gap look like a modelling deficit rather than a protocol
   difference.

Baseline rows are literature values and are marked as such; only our row is
computed. Writes docs/paper/main_results_table.tex.

Usage:
  python scripts/emit_main_results_table.py --results_dir results/local_20260803
"""

import argparse
import json
from pathlib import Path

import numpy as np

# Literature values, segment-level protocol. Sources cited in the caption.
BASELINES = [
    ('BERT-base',        '60.26', '89.68', '---'),
    ('LayoutLM-base',    '79.27', '94.72', '---'),
    ('LayoutLMv2-base',  '82.76', '94.95', '---'),
    ('LayoutLMv3-base~\\cite{huang2022layoutlmv3}',  '90.29', '96.56', '---'),
    ('LayoutLMv3-large', '92.08', '97.46', '---'),
    ('GeoLayoutLM~\\cite{luo2023geolayoutlm}', '92.86', '97.97', '---'),
    ('HGALayoutLM~\\cite{li2024hgalayoutlm}', '95.31', '97.67', '---'),
]
# No bold "winner" formatting anywhere in this table: the blocks are not a
# leaderboard (protocols and schemas differ) and must not read as one.
# Word-level re-annotated protocol (FUNSD-r / CORD-r).
WORD_LEVEL = [
    ('LayoutLMv3 seq.\\ lab.', '78.77', '82.72', '---'),
    ('TPP~\\cite{zhang2023readingorder}', '80.40', '91.85', '---'),
]


def seed_values(rd, ds):
    vals = []
    for name in (f'phase2_{ds}.json', f'phase2_{ds}_s123.json',
                 f'phase2_{ds}_s456.json'):
        p = Path(rd) / name
        if p.exists():
            vals.append(json.loads(p.read_text())['results']['test_metrics']['f1'] * 100)
    return vals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--results_dir', default='results/local_20260803')
    ap.add_argument('--output', default='docs/paper/main_results_table.tex')
    args = ap.parse_args()

    ours, ns = {}, {}
    for ds in ('funsd', 'cord', 'wildreceipt'):
        v = seed_values(args.results_dir, ds)
        if not v:
            ours[ds] = '---'; ns[ds] = 0; continue
        ns[ds] = len(v)
        ours[ds] = (f'{np.mean(v):.2f}\\,$\\pm$\\,{np.std(v):.2f}' if len(v) > 1
                    else f'{np.mean(v):.2f}')
    nseeds = max(ns.values()) if ns else 0

    rows = [f'{n} & {f} & {c} & {w} \\\\' for n, f, c, w in BASELINES]
    wrows = [f'{n} & {f} & {c} & {w} \\\\' for n, f, c, w in WORD_LEVEL]
    ours_row = (f'\\methodname{{}} (Ours) & {ours["funsd"]} & {ours["cord"]} & '
                f'{ours["wildreceipt"]} \\\\')

    tex = r"""% GENERATED by scripts/emit_main_results_table.py -- do not edit by hand.
\begin{table}[t]
\centering
\caption{Full historical backbone comparison (referenced from the main paper's
Table~1). F1 is not this paper's contribution and this table is not a
leaderboard.
Both literature blocks are \emph{reference values} under protocols that differ
from ours: the upper block uses \emph{segment-level} layout positions (all
words of a ground-truth segment share one 2D position, which LayoutLMv3's
authors note is not directly comparable to word-level work), and even the
word-level block differs in annotation source and schema (we use word-level
positions and the full 54-label CORD schema; most published CORD numbers use
the 30-field setting), and the word-level rows use a base-size backbone where
ours is large. Segment-level values are as tabulated in the LayoutLMv2 and
LayoutLMv3 comparison tables. Our row is mean $\pm$ std over """ + str(nseeds) + r""" training
seeds.}
\label{tab:supp_backbone_full}
\small
\setlength{\tabcolsep}{1.6pt}
\begin{tabular}{lccc}
\toprule
Model & FUNSD & CORD & WildRec. \\
\midrule
\multicolumn{4}{l}{\emph{Segment-level protocol (published, reference)}} \\
""" + '\n'.join(rows) + r"""
\midrule
\multicolumn{4}{l}{\emph{Word-level protocol (FUNSD-r / CORD-r, reference)}} \\
""" + '\n'.join(wrows) + r"""
\midrule
""" + ours_row + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    Path(args.output).write_text(tex)
    print(f'wrote {args.output}')
    for ds in ('funsd', 'cord', 'wildreceipt'):
        print(f'  {ds:<12} {ours[ds]}  ({ns[ds]} seeds)')


if __name__ == '__main__':
    main()
