#!/usr/bin/env python3
"""
Emit the E2 label-error-detector comparison as a LaTeX table.

Reads results/<tag>/label_error_baselines_*.json and produces
docs/paper/supp_label_error_table.tex.

The framing matters and is baked into the caption: mondrian_gap is
class-granular by construction (every token of a class receives that class's
coverage deficit), so it is NOT expected to win a token-level ranking metric.
The comparison establishes what each method is for, not which is uniformly
better. If Cleanlab wins on token-level ranking and per-class coverage wins on
localizing which CLASS is broken, that dissociation is the result -- and we
report it either way.

Usage:
  python scripts/emit_label_error_table.py --results_dir results/local_20260803
"""

import argparse
import json
from pathlib import Path

NICE = {
    'mondrian_gap': 'Per-class coverage deficit (ours)',
    'cleanlab': 'Cleanlab token classification~\\cite{wang2022tokenerrors}',
    'icp_pvalue': 'Inductive-CP $p$-value~\\cite{zhan2025cleaning}',
    'aum': 'AUM~\\cite{pleiss2020aum}',
    'datamap_conf': 'Data Maps confidence~\\cite{swayamdipta2020cartography}',
    'datamap_var': 'Data Maps variability~\\cite{swayamdipta2020cartography}',
    'max_softmax': 'Max-softmax baseline',
}
ORDER = ['mondrian_gap', 'cleanlab', 'icp_pvalue', 'aum',
         'datamap_conf', 'datamap_var', 'max_softmax']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--results_dir', default='results/local_20260803')
    ap.add_argument('--output', default='docs/paper/supp_label_error_table.tex')
    args = ap.parse_args()

    rd = Path(args.results_dir)
    files = sorted(p for p in rd.glob('label_error_baselines_*.json')
                   if 'LINEARPROBE' not in p.name)
    if not files:
        print('no E2 result files yet'); return

    runs = []
    for p in files:
        d = json.loads(p.read_text())
        runs.append(d)

    # one column block per run (noise model + eps)
    heads, keys = [], []
    for d in runs:
        _abbr = {'class_targeted': 'class-tgt', 'bio_shift': 'BIO-shift',
                 'uniform': 'uniform'}
        _nm = _abbr.get(d['noise_model'], d['noise_model'].replace('_', '-'))
        heads.append(f"{_nm} & $\\epsilon${d['eps']}" if False else
                     f"\\shortstack{{{_nm}\\\\$\\epsilon${{=}}{d['eps']}}}")
        keys.append(d)

    def cell(d, det):
        """AUPRC, plus the class-level rank of the truly-corrupted class when
        that metric is present. The two answer different questions and both are
        shown: token-level ranking, and class-level localisation."""
        r = d['detectors'].get(det, {})
        a = r.get('auprc')
        txt = f'{a:.3f}' if isinstance(a, (int, float)) else '---'
        cl = r.get('class_level') or {}
        rk = cl.get('rank_of_corrupted_class')
        if rk:
            txt += f' / {rk}'
        return txt

    rows = []
    for det in ORDER:
        rows.append(f'{NICE.get(det, det)} & '
                    + ' & '.join(cell(d, det) for d in keys) + r' \\')

    prev = ' / '.join(
        f"{d['n_planted_errors']/d['n_tokens']*100:.2f}\\%" for d in keys)
    accs = ' / '.join(
        f"{d.get('oof_accuracy_vs_noisy_labels', float('nan')):.3f}" for d in keys)
    ncol = 'l' + 'r' * len(keys)

    tex = r"""% GENERATED by scripts/emit_label_error_table.py -- do not edit by hand.
\begin{table*}[t]
\centering
\caption{Label-error detection under planted noise (AUPRC, higher is better;
random equals the error prevalence, """ + prev + r"""). All detectors consume the
same out-of-fold predicted probabilities from a model fine-tuned on the
\emph{noisy} labels---the setting confident learning assumes---with out-of-fold
accuracy """ + accs + r""" against those noisy labels, so no method is
advantaged by a better model. AUM and Data Maps additionally use training
dynamics from a single full-data fit. Our per-class coverage deficit is
class-granular by construction: every token of a class receives the same score,
so it cannot win a \emph{token}-level ranking metric and is not intended to. It
answers a different question---which class or schema is broken---which is the
level at which the CORD and SROIE defects actually live. Where a second number
is shown it is the \emph{class-level} rank of the truly corrupted class after
aggregating each detector's token scores to a per-class mean; the same
aggregation is applied to every detector, so no method is handicapped. Rank 1
means the detector placed the corrupted class at the top of the list.}
\label{tab:supp_label_error}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{""" + ncol + r"""}
\toprule
Detector & """ + ' & '.join(heads) + r""" \\
\midrule
""" + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
    Path(args.output).write_text(tex)
    print(f'wrote {args.output} ({len(runs)} runs, {len(ORDER)} detectors)')

    print(f'\n{"detector":<34}' + ''.join(f'{h:>22}' for h in heads))
    for det in ORDER:
        cells = []
        for d in keys:
            a = d['detectors'].get(det, {}).get('auprc')
            cells.append(f'{a:.4f}' if isinstance(a, (int, float)) else '  --')
        print(f'{det:<34}' + ''.join(f'{c:>22}' for c in cells))


if __name__ == '__main__':
    main()
